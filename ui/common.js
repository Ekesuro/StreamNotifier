function fmtViewers(n) {
  n = Number(n) || 0;
  if (n >= 1000) return (n / 1000).toFixed(n >= 10000 ? 0 : 1).replace(/\.0$/, "") + "K";
  return String(n);
}

function fmtUptime(iso) {
  const t = Date.parse(iso);
  if (!iso || isNaN(t)) return "";
  const mins = Math.max(0, Math.floor((Date.now() - t) / 60000));
  const h = Math.floor(mins / 60), m = mins % 60;
  return h ? `${h}h ${m}m` : `${m}m`;
}

function sortStreamers(list) {
  const rank = s => (s.state === "live" ? 0 : s.state === "offline" ? 1 : 2);
  return [...list].sort((a, b) =>
    rank(a) - rank(b) || (b.viewers || 0) - (a.viewers || 0) ||
    (a.display || a.name).localeCompare(b.display || b.name, undefined, { sensitivity: "base" }));
}

// Theme: "system" | "light" | "dark". Tells Python whether to darken the native title bar.
const darkQuery = matchMedia("(prefers-color-scheme: dark)");
let currentTheme = "system", lastDark = null;
function applyTheme(theme) {
  currentTheme = theme || "system";
  if (currentTheme === "system") delete document.documentElement.dataset.theme;
  else document.documentElement.dataset.theme = currentTheme;
  const dark = currentTheme === "dark" || (currentTheme === "system" && darkQuery.matches);
  if (dark !== lastDark) {
    lastDark = dark;
    window.pywebview?.api?.set_dark(dark);
  }
}
darkQuery.addEventListener("change", () => applyTheme(currentTheme));

function onApiReady(fn) {
  if (window.pywebview?.api) fn();
  else window.addEventListener("pywebviewready", fn, { once: true });
}
